    fecha_pago  DATE DEFAULT SYSDATE NOT NULL,
    monto_pago  NUMBER(12,2) NOT NULL,
    canal_pago  VARCHAR2(30) DEFAULT 'TARJETA DE CREDITO' NOT NULL,
    referencia  VARCHAR2(50),

    CONSTRAINT pk_av_pagos PRIMARY KEY (pago_id),
    CONSTRAINT fk_av_pago_res FOREIGN KEY (reserva_id)
