-- Hoteles (un hotel está en una ciudad, y la ciudad ya cuelga de un país)
CREATE TABLE av_hoteles (
    hotel_id    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre      VARCHAR2(60) NOT NULL,
    ciudad_id   NUMBER NOT NULL,
    direccion   VARCHAR2(120) NOT NULL,
    estrellas   NUMBER(1) NOT NULL,
    estado      VARCHAR2(15) DEFAULT 'ACTIVO' NOT NULL,

    CONSTRAINT pk_av_hoteles PRIMARY KEY (hotel_id),
    CONSTRAINT fk_av_hot_ciudad FOREIGN KEY (ciudad_id)
        REFERENCES av_ciudades (ciudad_id),
    CONSTRAINT ck_av_hot_estrellas CHECK (estrellas BETWEEN 1 AND 5),
    CONSTRAINT ck_av_hot_estado CHECK (estado IN ('ACTIVO', 'INACTIVO'))
);

-- Habitaciones (cada habitación pertenece a un hotel)
CREATE TABLE av_habitaciones (
    habitacion_id   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    hotel_id        NUMBER NOT NULL,
    num_habitacion  VARCHAR2(10) NOT NULL,
    tipo            VARCHAR2(20) NOT NULL,
    capacidad       NUMBER(2) NOT NULL,
    precio_noche    NUMBER(10,2) NOT NULL,
    estado          VARCHAR2(15) DEFAULT 'DISPONIBLE' NOT NULL,

    CONSTRAINT pk_av_habitaciones PRIMARY KEY (habitacion_id),
    CONSTRAINT fk_av_hab_hotel FOREIGN KEY (hotel_id)
        REFERENCES av_hoteles (hotel_id),
    CONSTRAINT uq_av_hab_num UNIQUE (hotel_id, num_habitacion),
    CONSTRAINT ck_av_hab_tipo CHECK (tipo IN ('SENCILLA', 'DOBLE', 'SUITE', 'FAMILIAR')),
    CONSTRAINT ck_av_hab_estado CHECK (estado IN ('DISPONIBLE', 'NO DISPONIBLE')),
    CONSTRAINT ck_av_hab_precio CHECK (precio_noche >= 0),
    CONSTRAINT ck_av_hab_cap CHECK (capacidad BETWEEN 1 AND 6)
);

-- Vuelos (oferta del catálogo: ruta, fecha y precio base)
CREATE TABLE av_vuelos (
    vuelo_id              NUMBER GENERATED BY DEFAULT AS IDENTITY,
    aerolinea_id          NUMBER NOT NULL,
    num_vuelo             VARCHAR2(10) NOT NULL,    -- AV245, LA830
    aeropuerto_origen_id  NUMBER NOT NULL,
    aeropuerto_destino_id NUMBER NOT NULL,
    fecha_salida          DATE NOT NULL,
    fecha_llegada         DATE NOT NULL,
    precio_base           NUMBER(10,2) NOT NULL,
    asientos_disponibles  NUMBER(4) NOT NULL,
    estado                VARCHAR2(15) DEFAULT 'PROGRAMADO' NOT NULL,

    CONSTRAINT pk_av_vuelos PRIMARY KEY (vuelo_id),
    CONSTRAINT fk_av_vue_aero FOREIGN KEY (aerolinea_id)
        REFERENCES av_aerolineas (aerolinea_id),
    CONSTRAINT fk_av_vue_origen FOREIGN KEY (aeropuerto_origen_id)
        REFERENCES av_aeropuertos (aeropuerto_id),
    CONSTRAINT fk_av_vue_destino FOREIGN KEY (aeropuerto_destino_id)
        REFERENCES av_aeropuertos (aeropuerto_id),
    CONSTRAINT uq_av_vue_num_fecha UNIQUE (aerolinea_id, num_vuelo, fecha_salida),
    CONSTRAINT ck_av_vue_ruta CHECK (aeropuerto_origen_id <> aeropuerto_destino_id),
    CONSTRAINT ck_av_vue_fechas CHECK (fecha_llegada > fecha_salida),
    CONSTRAINT ck_av_vue_precio CHECK (precio_base >= 0),
    CONSTRAINT ck_av_vue_asientos CHECK (asientos_disponibles >= 0),
    CONSTRAINT ck_av_vue_estado CHECK (estado IN
        ('PROGRAMADO', 'EN VUELO', 'COMPLETADO', 'CANCELADO'))
);

-- Transporte terrestre (bus, tren, van entre ciudades)
CREATE TABLE av_transportes_terrestres (
    transporte_id      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    tipo               VARCHAR2(10) NOT NULL,
    empresa            VARCHAR2(60) NOT NULL,
    ciudad_origen_id   NUMBER NOT NULL,
    ciudad_destino_id  NUMBER NOT NULL,
    fecha_salida       DATE NOT NULL,
    fecha_llegada      DATE NOT NULL,
    precio             NUMBER(10,2) NOT NULL,
    cupos_disponibles  NUMBER(3) NOT NULL,
    estado             VARCHAR2(15) DEFAULT 'PROGRAMADO' NOT NULL,

    CONSTRAINT pk_av_transp PRIMARY KEY (transporte_id),
    CONSTRAINT fk_av_transp_origen FOREIGN KEY (ciudad_origen_id)
        REFERENCES av_ciudades (ciudad_id),
    CONSTRAINT fk_av_transp_destino FOREIGN KEY (ciudad_destino_id)
        REFERENCES av_ciudades (ciudad_id),
    CONSTRAINT ck_av_transp_tipo CHECK (tipo IN ('BUS', 'TREN', 'VAN')),
    CONSTRAINT ck_av_transp_ruta CHECK (ciudad_origen_id <> ciudad_destino_id),
    CONSTRAINT ck_av_transp_fechas CHECK (fecha_llegada > fecha_salida),
    CONSTRAINT ck_av_transp_precio CHECK (precio >= 0),
    CONSTRAINT ck_av_transp_cupos CHECK (cupos_disponibles >= 0),
    CONSTRAINT ck_av_transp_estado CHECK (estado IN
        ('PROGRAMADO', 'EN RUTA', 'COMPLETADO', 'CANCELADO'))
);

------------------------------------------------------------ RESERVAS ------------------------------------------------------------
-- Reserva: cabecera del viaje completo (un cliente titular)
CREATE TABLE av_reservas (
    reserva_id         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    cliente_id         NUMBER NOT NULL,     -- titular / pagador
    fecha_reserva      DATE DEFAULT SYSDATE NOT NULL,
    fecha_inicio_viaje DATE NOT NULL,
    fecha_fin_viaje    DATE NOT NULL,
    monto_total        NUMBER(12,2) NOT NULL,
    estado             VARCHAR2(20) DEFAULT 'ACTIVA' NOT NULL,

    CONSTRAINT pk_av_reservas PRIMARY KEY (reserva_id),
    CONSTRAINT fk_av_res_cli FOREIGN KEY (cliente_id)
        REFERENCES av_clientes (cliente_id),
    CONSTRAINT ck_av_res_fechas CHECK (fecha_fin_viaje > fecha_inicio_viaje),
    CONSTRAINT ck_av_res_inicio CHECK (fecha_inicio_viaje >= fecha_reserva),
    CONSTRAINT ck_av_res_monto CHECK (monto_total >= 0),
    CONSTRAINT ck_av_res_estado CHECK (estado IN
        ('ACTIVA', 'CONFIRMADA', 'CANCELADA', 'COMPLETADA', 'NO SHOW'))
);

-- Pasajeros de la reserva: REGLA CLAVE

CREATE TABLE av_reserva_pasajeros (
    reserva_id    NUMBER NOT NULL,
    num_pasajero  NUMBER(1) NOT NULL,
    cliente_id    NUMBER NOT NULL,

    CONSTRAINT pk_av_res_pas PRIMARY KEY (reserva_id, num_pasajero),
    CONSTRAINT fk_av_res_pas_res FOREIGN KEY (reserva_id)
        REFERENCES av_reservas (reserva_id),
    CONSTRAINT fk_av_res_pas_cli FOREIGN KEY (cliente_id)
        REFERENCES av_clientes (cliente_id),
    CONSTRAINT uq_av_res_pas_cli UNIQUE (reserva_id, cliente_id),  -- no duplicar
    CONSTRAINT ck_av_res_pas_num CHECK (num_pasajero IN (1, 2))
);

-- Vuelos incluidos en la reserva (una reserva puede tener 0..N vuelos: ida, regreso, escalas)
CREATE TABLE av_reserva_vuelos (
    detalle_id       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    reserva_id       NUMBER NOT NULL,   
    vuelo_id         NUMBER NOT NULL,
    precio_aplicado  NUMBER(10,2) NOT NULL,
    estado           VARCHAR2(15) DEFAULT 'ACTIVO' NOT NULL,

    CONSTRAINT pk_av_res_vue PRIMARY KEY (detalle_id),
    CONSTRAINT fk_av_resvue_res FOREIGN KEY (reserva_id)
        REFERENCES av_reservas (reserva_id),
    CONSTRAINT fk_av_resvue_vue FOREIGN KEY (vuelo_id)
        REFERENCES av_vuelos (vuelo_id),
    CONSTRAINT uq_av_resvue UNIQUE (reserva_id, vuelo_id),
    CONSTRAINT ck_av_resvue_precio CHECK (precio_aplicado >= 0),
    CONSTRAINT ck_av_resvue_estado CHECK (estado IN ('ACTIVO', 'CANCELADO'))
);

-- Hospedajes incluidos en la reserva
CREATE TABLE av_reserva_hospedajes (
    detalle_id      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    reserva_id      NUMBER NOT NULL,
    habitacion_id   NUMBER NOT NULL,
    fecha_checkin   DATE NOT NULL,
    fecha_checkout  DATE NOT NULL,
    num_noches      NUMBER(3) NOT NULL,
    precio_total    NUMBER(10,2) NOT NULL,
    estado          VARCHAR2(15) DEFAULT 'ACTIVO' NOT NULL,

    CONSTRAINT pk_av_res_hos PRIMARY KEY (detalle_id),
    CONSTRAINT fk_av_reshos_res FOREIGN KEY (reserva_id)
        REFERENCES av_reservas (reserva_id),
    CONSTRAINT fk_av_reshos_hab FOREIGN KEY (habitacion_id)
        REFERENCES av_habitaciones (habitacion_id),
    CONSTRAINT ck_av_reshos_fechas CHECK (fecha_checkout > fecha_checkin),
    CONSTRAINT ck_av_reshos_noches CHECK (num_noches > 0),
    CONSTRAINT ck_av_reshos_precio CHECK (precio_total >= 0),
    CONSTRAINT ck_av_reshos_estado CHECK (estado IN ('ACTIVO', 'CANCELADO'))
);

-- Transportes terrestres incluidos en la reserva
CREATE TABLE av_reserva_transportes (
    detalle_id       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    reserva_id       NUMBER NOT NULL,
    transporte_id    NUMBER NOT NULL,
    precio_aplicado  NUMBER(10,2) NOT NULL,
    estado           VARCHAR2(15) DEFAULT 'ACTIVO' NOT NULL,

    CONSTRAINT pk_av_res_tra PRIMARY KEY (detalle_id),
    CONSTRAINT fk_av_restra_res FOREIGN KEY (reserva_id)
        REFERENCES av_reservas (reserva_id),
    CONSTRAINT fk_av_restra_tra FOREIGN KEY (transporte_id)
        REFERENCES av_transportes_terrestres (transporte_id),
    CONSTRAINT uq_av_restra UNIQUE (reserva_id, transporte_id),
    CONSTRAINT ck_av_restra_precio CHECK (precio_aplicado >= 0),
    CONSTRAINT ck_av_restra_estado CHECK (estado IN ('ACTIVO', 'CANCELADO'))
);

