    CONSTRAINT ck_av_pago_monto CHECK (monto_pago >= 0),
    CONSTRAINT ck_av_pago_canal CHECK (canal_pago IN
        ('TARJETA DE CREDITO', 'TARJETA DEBITO', 'PSE', 'TRANSFERENCIA', 'EFECTIVO'))
);

CREATE TABLE av_notas_cancelacion (
    nota_id           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    reserva_id        NUMBER NOT NULL,
    fecha_nota        DATE DEFAULT SYSDATE NOT NULL,
    monto_devolucion  NUMBER(12,2) NOT NULL,
    motivo            VARCHAR2(60) DEFAULT 'CANCELACION VOLUNTARIA' NOT NULL,

    CONSTRAINT pk_av_notas PRIMARY KEY (nota_id),
    CONSTRAINT fk_av_nota_res FOREIGN KEY (reserva_id)
        REFERENCES av_reservas (reserva_id),
    CONSTRAINT ck_av_nota_monto CHECK (monto_devolucion >= 0)
);


