-- Países (portafolio real: Colombia, México, España, etc.)
CREATE TABLE av_paises (
    pais_id      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    codigo_iso   VARCHAR2(3) NOT NULL,   -- ISO 3166-1 alpha-3: COL, MEX, USA
    nombre       VARCHAR2(60) NOT NULL,
    continente   VARCHAR2(20) NOT NULL,
    estado       VARCHAR2(15) DEFAULT 'ACTIVO' NOT NULL,

    CONSTRAINT pk_av_paises PRIMARY KEY (pais_id),
    CONSTRAINT uq_av_pais_iso UNIQUE (codigo_iso),
    CONSTRAINT uq_av_pais_nombre UNIQUE (nombre),
    CONSTRAINT ck_av_pais_estado CHECK (estado IN ('ACTIVO', 'INACTIVO')),
    CONSTRAINT ck_av_pais_continente CHECK (continente IN
        ('AMERICA', 'EUROPA', 'ASIA', 'AFRICA', 'OCEANIA', 'ANTARTIDA'))
);

-- Ciudades (cada ciudad pertenece a un país)
CREATE TABLE av_ciudades (
    ciudad_id   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    pais_id     NUMBER NOT NULL,
    nombre      VARCHAR2(60) NOT NULL,
    estado      VARCHAR2(15) DEFAULT 'ACTIVA' NOT NULL,

    CONSTRAINT pk_av_ciudades PRIMARY KEY (ciudad_id),
    CONSTRAINT fk_av_ciudad_pais FOREIGN KEY (pais_id)
        REFERENCES av_paises (pais_id),
    CONSTRAINT uq_av_ciudad_pais UNIQUE (pais_id, nombre),
    CONSTRAINT ck_av_ciudad_estado CHECK (estado IN ('ACTIVA', 'INACTIVA'))
);

-- Aerolíneas
CREATE TABLE av_aerolineas (
    aerolinea_id  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    codigo_iata   VARCHAR2(3) NOT NULL,    -- AV (Avianca), LA (Latam), etc.
    nombre        VARCHAR2(60) NOT NULL,
    pais_id       NUMBER NOT NULL,         -- país de origen
    estado        VARCHAR2(15) DEFAULT 'ACTIVA' NOT NULL,

    CONSTRAINT pk_av_aerolineas PRIMARY KEY (aerolinea_id),
    CONSTRAINT fk_av_aero_pais FOREIGN KEY (pais_id)
        REFERENCES av_paises (pais_id),
    CONSTRAINT uq_av_aero_iata UNIQUE (codigo_iata),
    CONSTRAINT ck_av_aero_estado CHECK (estado IN ('ACTIVA', 'INACTIVA'))
);

-- Aeropuertos
CREATE TABLE av_aeropuertos (
    aeropuerto_id  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    codigo_iata    VARCHAR2(3) NOT NULL,   -- MDE, BOG, JFK
    nombre         VARCHAR2(80) NOT NULL,
    ciudad_id      NUMBER NOT NULL,
    estado         VARCHAR2(15) DEFAULT 'ACTIVO' NOT NULL,

    CONSTRAINT pk_av_aeropuertos PRIMARY KEY (aeropuerto_id),
    CONSTRAINT fk_av_aerop_ciudad FOREIGN KEY (ciudad_id)
        REFERENCES av_ciudades (ciudad_id),
    CONSTRAINT uq_av_aerop_iata UNIQUE (codigo_iata),
    CONSTRAINT ck_av_aerop_estado CHECK (estado IN ('ACTIVO', 'INACTIVO'))
);

